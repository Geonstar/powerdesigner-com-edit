#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
PowerDesigner Workspace Manager (.sws / .pbw)
Provides automated workspace discovery, model registration, folder grouping,
and directory synchronization.
Ensures every individually saved model file (.oom, .pdm) is neatly aggregated into
a PowerDesigner Workspace for easy project-wide navigation.
"""

import os
import uuid
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Optional, List, Dict, Any

from .config import get_config, WorkspaceConfig

# Known PowerDesigner Workspace Model Type GUIDs
WORKSPACE_MODEL_TYPE_OOM = "{18112060-1A4B-11D1-83D9-444553540000}"
WORKSPACE_MODEL_TYPE_PDM = "{CDE44E21-3017-11D2-8A2D-00609756FE6C}"
WORKSPACE_MODEL_TYPE_CDM = "{9C84FDF4-9E0C-11D1-A1DE-0020AF12A261}"


class WorkspaceManager:
    """
    Manages PowerDesigner Workspaces (.sws / .pbw).
    Supports:
    1. Active COM Workspace introspection and synchronization
    2. Local workspace file (.sws) discovery across directory hierarchy
    3. Standalone XML-level registration of new model documents
    4. Grouping models by virtual folders (e.g. Subsystems, UseCases)
    5. Batch directory scanning and synchronization (scan_and_sync)
    6. Auto-creation of project workspace when none exists
    """

    def __init__(self, workspace_path: Optional[str] = None, client: Optional[Any] = None):
        self.client = client
        self.config = get_config().workspace
        self.workspace_path = workspace_path or self._resolve_workspace_path()

    def _resolve_workspace_path(self) -> Optional[str]:
        """Attempt to discover workspace from config, active COM, or local filesystem."""
        # 1. Config explicit path
        if self.config.workspace_path and os.path.exists(self.config.workspace_path):
            return os.path.abspath(self.config.workspace_path)

        # 2. Check COM ActiveWorkspace if client is available
        if self.client and hasattr(self.client, "app") and self.client.app:
            try:
                ws = getattr(self.client.app, "ActiveWorkspace", None)
                if ws and hasattr(ws, "Filename") and ws.Filename:
                    return os.path.abspath(ws.Filename)
            except Exception:
                pass

        # 3. Search current working directory and output directory
        search_dirs = [
            Path.cwd(),
            Path(get_config().file_naming.output_dir).resolve(),
            Path.cwd().parent,
        ]
        for d in search_dirs:
            if d.exists():
                for ext in ("*.sws", "*.pbw"):
                    matches = list(d.glob(ext))
                    if matches:
                        return str(matches[0].resolve())

        return None

    def find_or_create_workspace(self, target_dir: Optional[str] = None, name: Optional[str] = None) -> str:
        """Find existing workspace file, or create a new one in target_dir."""
        if self.workspace_path and os.path.exists(self.workspace_path):
            return self.workspace_path

        ws_dir = Path(target_dir or get_config().file_naming.output_dir).resolve()
        ws_dir.mkdir(parents=True, exist_ok=True)
        ws_name = name or self.config.workspace_name or "ProjectWorkspace"
        new_path = ws_dir / f"{ws_name}.sws"

        self.create_workspace(str(new_path), name=ws_name)
        self.workspace_path = str(new_path)
        return self.workspace_path

    @staticmethod
    def create_workspace(filepath: str, name: str = "ProjectWorkspace") -> str:
        """Create a fresh .sws workspace file."""
        abs_path = os.path.abspath(filepath)
        os.makedirs(os.path.dirname(abs_path), exist_ok=True)

        content = (
            '<?xml version="1.0" encoding="UTF-8"?>\n'
            '<?PowerDesigner signature="Workspace" version="16.5.0.3982"?>\n'
            '<!-- do not edit this file -->\n\n'
            '<Workspace>\n'
            '\t<Local Expanded="Yes" Selected="Yes">\n'
            '\t</Local>\n'
            '\t<BrowserModule Name="仓库(&amp;R)"/>\n'
            '</Workspace>\n'
        )

        with open(abs_path, "w", encoding="utf-8") as f:
            f.write(content)
        return abs_path

    def register_model(
        self,
        model_path: str,
        model_name: Optional[str] = None,
        model_type: str = "OOM",
        folder: Optional[str] = None,
        expanded: bool = True
    ) -> bool:
        """
        Register a saved model file (.oom / .pdm) into the workspace.
        Optionally groups the model under a virtual folder node.
        """
        abs_model_path = os.path.abspath(model_path)
        if not os.path.exists(abs_model_path):
            return False

        if not model_name:
            model_name = Path(abs_model_path).stem

        ws_file = self.workspace_path
        if not ws_file or not os.path.exists(ws_file):
            if self.config.auto_create:
                ws_file = self.find_or_create_workspace(
                    target_dir=os.path.dirname(abs_model_path),
                    name=self.config.workspace_name
                )
            else:
                return False

        try:
            return self._register_in_sws_file(
                ws_file, abs_model_path, model_name, model_type, folder=folder, expanded=expanded
            )
        except Exception as e:
            print(f"[WorkspaceManager] Error registering model: {e}")
            return False

    def _register_in_sws_file(
        self,
        sws_path: str,
        model_abs_path: str,
        model_name: str,
        model_type: str,
        folder: Optional[str] = None,
        expanded: bool = True
    ) -> bool:
        """Parse .sws XML and insert <Model> node (optionally inside <Folder>)."""
        tree = ET.parse(sws_path)
        root = tree.getroot()

        local_node = root.find("Local")
        if local_node is None:
            local_node = ET.SubElement(root, "Local", {"Expanded": "Yes", "Selected": "Yes"})

        # Calculate relative URL between .sws and the model file
        sws_dir = os.path.dirname(os.path.abspath(sws_path))
        try:
            rel_url = os.path.relpath(model_abs_path, sws_dir).replace("\\", "/")
        except ValueError:
            rel_url = model_abs_path.replace("\\", "/")

        # Target parent node: either local_node or a specific Folder node
        target_parent = local_node
        if folder:
            # Find or create folder node
            folder_node = None
            for f in local_node.findall("Folder"):
                if f.get("Name") == folder:
                    folder_node = f
                    break
            if folder_node is None:
                folder_node = ET.SubElement(local_node, "Folder", {"Expanded": "Yes", "Name": folder})
            target_parent = folder_node

        # Check if already present anywhere in the workspace
        for m in local_node.iter("Model"):
            url = m.get("URL", "")
            if url == rel_url or url == model_abs_path.replace("\\", "/"):
                m.set("Name", model_name)
                self._write_sws_xml(root, sws_path)
                return True

        # Choose type GUID
        type_upper = model_type.upper()
        if "PDM" in type_upper:
            type_guid = WORKSPACE_MODEL_TYPE_PDM
        elif "CDM" in type_upper:
            type_guid = WORKSPACE_MODEL_TYPE_CDM
        else:
            type_guid = WORKSPACE_MODEL_TYPE_OOM

        model_id = f"{{{str(uuid.uuid4()).upper()}}}"
        attribs = {
            "ID": model_id,
            "Name": model_name,
            "Type": type_guid,
            "URL": rel_url,
        }
        if expanded:
            attribs["Expanded"] = "Yes"

        ET.SubElement(target_parent, "Model", attribs)
        self._write_sws_xml(root, sws_path)
        return True

    @staticmethod
    def _write_sws_xml(root: ET.Element, path: str):
        """Format and write .sws file with PowerDesigner header and proper indentation."""
        # Ensure BrowserModule exists
        if root.find("BrowserModule") is None:
            ET.SubElement(root, "BrowserModule", {"Name": "仓库(&amp;R)"})

        if hasattr(ET, "indent"):
            ET.indent(root, space="\t")

        xml_body = ET.tostring(root, encoding="utf-8").decode("utf-8")
        # Replace escaped ampersand in BrowserModule if double-escaped
        xml_body = xml_body.replace("&amp;amp;R", "&amp;R")

        header = (
            '<?xml version="1.0" encoding="UTF-8"?>\n'
            '<?PowerDesigner signature="Workspace" version="16.5.0.3982"?>\n'
            '<!-- do not edit this file -->\n\n'
        )

        with open(path, "w", encoding="utf-8") as f:
            f.write(header + xml_body + "\n")

    def scan_and_sync(self, directory: Optional[str] = None, folder: Optional[str] = None) -> List[str]:
        """
        Scan a target directory for all .oom, .pdm, and .cdm models,
        and register any unregistered models into the workspace.
        Returns a list of newly registered model file paths.
        """
        target_dir = Path(directory or get_config().file_naming.output_dir).resolve()
        if not target_dir.exists():
            return []

        registered = []
        extensions = {".oom": "OOM", ".pdm": "PDM", ".cdm": "CDM"}

        for ext, mtype in extensions.items():
            for file_path in target_dir.glob(f"*{ext}"):
                if self.register_model(str(file_path), model_type=mtype, folder=folder):
                    registered.append(str(file_path.resolve()))

        return registered

    def list_models(self) -> List[Dict[str, str]]:
        """List all models currently listed in this workspace, with their folder context."""
        if not self.workspace_path or not os.path.exists(self.workspace_path):
            return []

        tree = ET.parse(self.workspace_path)
        root = tree.getroot()
        local_node = root.find("Local")
        if local_node is None:
            return []

        res = []
        # Root models
        for m in local_node.findall("Model"):
            res.append({
                "id": m.get("ID", ""),
                "name": m.get("Name", ""),
                "type": m.get("Type", ""),
                "url": m.get("URL", ""),
                "folder": "",
            })

        # Models inside Folders
        for f in local_node.findall("Folder"):
            f_name = f.get("Name", "")
            for m in f.findall("Model"):
                res.append({
                    "id": m.get("ID", ""),
                    "name": m.get("Name", ""),
                    "type": m.get("Type", ""),
                    "url": m.get("URL", ""),
                    "folder": f_name,
                })

        return res
